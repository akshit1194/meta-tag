import hashlib
import json
import os
import tempfile
import uuid
from pathlib import Path

from flask import current_app

from .db import get_db
from .metadata import extract_metadata, server_now, signature_format
from .process import WorkerError, run_worker


class UploadError(Exception):
    def __init__(self, code, status=400):
        self.code, self.status = code, status
        super().__init__(code)


def save_upload(file, owner_id):
    config = current_app.config
    root = config['DATA_ROOT']
    slots = current_app.extensions['photo_slots']
    if not slots.acquire(blocking=False):
        raise UploadError('UPLOAD_BUSY', 503)
    # UUIDs generated by the server are the only persistent storage names.
    photo_id = uuid.uuid4().hex
    original_destination = root / 'originals' / photo_id
    display_destination = root / 'display' / (photo_id + '.jpg')
    committed = False
    try:
        with tempfile.TemporaryDirectory(prefix='upload-', dir=root / 'tmp') as temp:
            source = Path(temp) / 'source.bin'
            display = Path(temp) / 'display.jpg'
            uploaded_at = server_now()  # Server receipt time, never a capture-time fallback.
            digest = hashlib.sha256()
            size = 0
            with source.open('xb') as output:
                while chunk := file.stream.read(64 * 1024):
                    size += len(chunk)
                    if size > config['MAX_UPLOAD_BYTES']:
                        raise UploadError('FILE_TOO_LARGE', 413)
                    digest.update(chunk)
                    output.write(chunk)
            if not size:
                raise UploadError('EMPTY_FILE')
            image_format = signature_format(source)
            if not image_format:
                raise UploadError('UNSUPPORTED_FORMAT', 415)

            # Ordering is deliberate: original bytes -> EXIF -> decode/resize/encode.
            metadata = extract_metadata(source, image_format, size, config)
            try:
                details = run_worker(
                    dict(action='display', path=str(source), output=str(display),
                         format=image_format, max_pixels=config['MAX_IMAGE_PIXELS'],
                         orientation=metadata['fields']['image']['orientation']),
                    timeout=config['WORKER_TIMEOUT'], memory_mb=config['WORKER_MEMORY_MB'],
                )
            except WorkerError as error:
                status = 503 if error.code in ('RESOURCE_LIMIT_SETUP_FAILED', 'WORKER_FAILED', 'WORKER_START_FAILED') else 400
                raise UploadError(error.code, status) from None
            metadata['fields']['image'].update(width=details['width'], height=details['height'])
            if details['multiple_frames']:
                metadata['warnings'].append('PRIMARY_FRAME_DISPLAYED')
            os.replace(display, display_destination)
            retained = config['RETAIN_ORIGINALS']
            if retained:
                os.replace(source, original_destination)
            db = get_db()
            try:
                db.execute(
                    'INSERT INTO photos(id,owner_id,uploaded_at,format,byte_size,width,height,original_retained) '
                    'VALUES (?,?,?,?,?,?,?,?)',
                    (photo_id, owner_id, uploaded_at, image_format, size, details['width'], details['height'], int(retained)),
                )
                db.execute(
                    'INSERT INTO photo_metadata(photo_id,status,uploaded_at,sha256,fields_json,warnings_json,error_code) '
                    'VALUES (?,?,?,?,?,?,?)',
                    (photo_id, metadata['status'], uploaded_at, digest.hexdigest(),
                     json.dumps(metadata['fields'], allow_nan=False), json.dumps(metadata['warnings']), metadata['error_code']),
                )
                db.commit()
                committed = True
            except Exception:
                db.rollback()
                raise
        return photo_id
    finally:
        if not committed:
            display_destination.unlink(missing_ok=True)
            original_destination.unlink(missing_ok=True)
        slots.release()
